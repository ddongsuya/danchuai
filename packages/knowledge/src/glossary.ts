export function expandQuery(q: string): string {
  const low = q.toLowerCase();
  const extra = GLOSSARY.filter(([ko]) => low.includes(ko)).map(([, en]) => en);
  return extra.length ? `${q} ${extra.join(" ")}` : q;
}
